def convert_to_pahadi(hindi_text: str) -> str:
    # Step 1 — apply extra replacements (longer phrases first)
    sorted_extra = sorted(EXTRA_REPLACEMENTS.keys(), key=len, reverse=True)
    for word in sorted_extra:
        if word in hindi_text:
            hindi_text = hindi_text.replace(word, EXTRA_REPLACEMENTS[word])

    # Step 2 — apply main dictionary (longer keys first)
    sorted_keys = sorted(PAHADI_DICT.keys(), key=len, reverse=True)
    for word in sorted_keys:
        if word in hindi_text:
            hindi_text = hindi_text.replace(word, PAHADI_DICT[word])

    return hindi_text